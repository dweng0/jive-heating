def prefix(selectors):
    return ", ".join(".live-page" if x.strip() in (":root", "body") else f".live-page {x.strip()}" for x in selectors.split(","))


def scope(block):
    out, i = [], 0
    while True:
        m = re.search(r"([^{}]+)\{", block[i:])
        if not m:
            break
        sel = m.group(1).strip()
        start = i + m.end()
        depth, j = 1, start
        while depth:
            depth += {"{": 1, "}": -1}.get(block[j], 0)
            j += 1
        body = block[start:j - 1]
        if sel.startswith("@keyframes"):
            out.append(f"{sel} {{{body}}}")
        elif sel.startswith("@media"):
            out.append(f"{sel} {{ {scope(body)} }}")
        elif sel in ("*", "html, body"):
            pass
        else:
            out.append(f"{prefix(sel)} {{{body.strip()} }}")
        i = j
    return "\n".join(out)


